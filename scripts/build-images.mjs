import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);

export async function buildImages() {
  const source = new URL('images/', root);
  const output = new URL('dist/images/', root);
  const references = JSON.parse(await readFile(new URL('image-references.json', root), 'utf8'));
  const names = (await readdir(source, { withFileTypes: true }))
    .filter(entry => entry.isFile() && /\.(?:jpe?g|png|webp|gif|avif)$/i.test(entry.name))
    .map(entry => entry.name).sort();
  const files = Object.create(null);
  const originals = new Map();
  await mkdir(output, { recursive: true });
  // NFCでコピーし、Windowsと公開先Linuxで濁点の表現が違っても一致させます。
  for (const name of names) {
    const normalized = name.normalize('NFC');
    if (originals.has(normalized)) throw new Error('正規化後の画像名が重複しています: ' + normalized);
    originals.set(normalized, name);
    files[normalized] = 'images/' + encodeURIComponent(normalized);
    await copyFile(new URL(encodeURIComponent(name), source), new URL(encodeURIComponent(normalized), output));
  }
  const aliases = [];
  const missing = [];
  const unassigned = [];
  const legacyByName = Object.create(null);
  for (const item of references.items) {
    const reference = item.image.trim().normalize('NFC');
    legacyByName[item.name.normalize('NFC')] = reference;
    if (!reference) {
      unassigned.push(item.name);
      continue;
    }
    if (files[reference] || /^https?:\/\//i.test(reference)) continue;
    // jpgとjpegは同じ形式。画像名の曖昧な部分一致は行いません。
    const candidates = [...originals.keys()].filter(name => /\.jpe?g$/i.test(name) &&
      /\.jpe?g$/i.test(reference) && name.replace(/\.jpe?g$/i, '') === reference.replace(/\.jpe?g$/i, ''));
    if (candidates.length === 1) {
      files[reference] = files[candidates[0]];
      aliases.push({ name: item.name, reference, file: candidates[0] });
    } else missing.push({ name: item.name, reference });
  }
  const manifest = { source: references.source, files, legacyByName };
  await writeFile(new URL('dist/images.js', root), '/* Generated by scripts/build-images.mjs. */\nglobalThis.MapImages = ' + JSON.stringify(manifest, null, 2) + ';\n');
  return { copied: names.length, matched: references.items.filter(item => item.image && files[item.image.normalize('NFC')]).length, aliases, missing, unassigned };
}
